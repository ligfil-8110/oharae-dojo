export function getPresetSections(preset: PresetId, includeFramingLines: boolean): Section[] {
  const result: Section[] = [];

  if (preset === 'noru' && includeFramingLines) {
    result.push(OPENING_SECTION);
  }

  result.push(...CORE_SECTIONS);

  if (preset === 'noru') {
    const closing: Section = {
      ...CLOSING_NORU,
      phrases: includeFramingLines
        ? [...CLOSING_NORU.phrases, CLOSING_NORU_FRAMING_EXTRA]
        : [...CLOSING_NORU.phrases],
    };
    result.push(closing);
  } else {
    result.push(CLOSING_MAOSU);
  }

  return result;
}

